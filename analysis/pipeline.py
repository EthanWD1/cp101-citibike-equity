"""Run the entire offline analysis from unchanged raw inputs."""
import argparse
import importlib.metadata
import json
import platform
import time
from pathlib import Path

import pandas as pd

from .config import RAW, PROCESSED, SOURCES
from .download_data import checksum
from .trips import aggregate_trips
from .geography import load_tracts, locate_stations, locate_coordinate_starts
from .metrics import calculate_metrics, validate_results
from .visualize import create_figures


def write_csv(frame, name):
    frame.to_csv(PROCESSED / name, index=False, float_format="%.10g")


def write_cleaning_notes(ledger, validation):
    lines = ["# Cleaning and assignment audit", "",
             "Generated by `python -m analysis.pipeline` from all six raw trip CSVs. No sampling is used.", "",
             "The trip exclusion rows are sequential and disjoint. Endpoint, ACS, and comparison rows refer to different populations; do not sum them as discarded trips. Unavailable ACS values remain missing, never zero.", "",
             "| Stage | Operation | Before | Affected | After | Action / justification |",
             "|---|---|---:|---:|---:|---|"]
    for row in ledger:
        lines.append(f"| {row['stage']} | {row['step']} | {row['before']:,} | {row['affected']:,} | {row['after']:,} | {row['action']}: {row['reason']} |")
    lines += ["", "## Reconciliation", ""]
    lines += [f"- {key}: **{value:,}**" for key, value in validation["counts"].items()]
    lines += ["", "## Validation", ""]
    lines += [f"- {key}: {'PASS' if value else 'FAIL'}" for key, value in validation["checks"].items()]
    Path("docs/cleaning_audit.md").write_text("\n".join(lines) + "\n")


def run(make_report=True, chunk_size=200_000):
    started = time.perf_counter()
    if not RAW.exists():
        raise FileNotFoundError("Run from the project root; first run python -m analysis.download_data")
    manifest = json.loads((RAW / "sources.json").read_text())
    for name in SOURCES:
        if not (RAW / name).is_file():
            raise FileNotFoundError(f"Missing {RAW / name}; run python -m analysis.download_data")
        if checksum(RAW / name) != manifest[name]["sha256"]:
            raise ValueError(f"Raw source checksum mismatch: {name}")
    PROCESSED.mkdir(parents=True, exist_ok=True)
    Path("docs").mkdir(exist_ok=True)
    print("Verified all source checksums; processing the complete month.", flush=True)
    trips = aggregate_trips(chunk_size=chunk_size)
    ledger = trips["ledger"]
    tracts = load_tracts(ledger)
    stations, endpoint_audit = locate_stations(trips["endpoints"], tracts)
    coordinates = locate_coordinate_starts(trips["coordinate_only"], tracts)
    for side in ["start", "end"]:
        for field in [f"missing_{side}_id", f"invalid_{side}_coordinates"]:
            ledger.append(dict(stage="endpoint_audit", step=field, before=trips["totals"]["retained_september"],
                               affected=int(trips["missingness"][field].sum()), after=trips["totals"]["retained_september"],
                               action="flag_endpoint", reason="Does not itself remove the trip; canonical station locations can recover starts with valid station IDs"))
    ledger.append(dict(stage="spatial_join", step="station_outside_or_unmatched_nyc", before=len(stations),
                       affected=int(stations.GEOID.isna().sum()), after=int(stations.GEOID.notna().sum()),
                       action="exclude_from_nyc", reason="Station point does not intersect a NYC tract; no nearest-tract snapping"))
    tracts, daily, thresholds, comparisons, correlations, boroughs = calculate_metrics(tracts, stations, trips["station_daily"], ledger)
    validation = validate_results(trips, tracts, stations, daily, coordinates)
    validation["quartile_thresholds"] = thresholds
    validation["runtime_seconds"] = round(time.perf_counter() - started, 2)
    validation["python"] = platform.python_version()
    validation["packages"] = {p: importlib.metadata.version(p) for p in ["pandas", "numpy", "geopandas", "matplotlib", "scipy"]}
    write_csv(tracts.drop(columns="geometry"), "tract_metrics.csv")
    # Replace rather than append: reruns have one layer with identical schema.
    spatial = PROCESSED / "tract_metrics.gpkg"
    spatial.unlink(missing_ok=True)
    tracts.to_file(spatial, layer="tracts", driver="GPKG", index=False)
    write_csv(stations.drop(columns="geometry"), "observed_stations.csv")
    write_csv(endpoint_audit, "station_coordinate_audit.csv")
    write_csv(stations.loc[stations.location_review_flag].drop(columns="geometry"), "station_location_flags.csv")
    write_csv(stations.loc[stations.GEOID.isna()].drop(columns="geometry"), "unmatched_stations.csv")
    write_csv(daily, "station_daily_departures.csv")
    write_csv(daily.loc[daily.GEOID.isna()], "unassigned_station_departures.csv")
    write_csv(coordinates, "coordinate_only_starts.csv")
    write_csv(trips["missingness"], "missingness_by_date_category.csv")
    write_csv(trips["raw_date_audit"], "raw_date_category_audit.csv")
    write_csv(trips["files"], "trip_file_audit.csv")
    write_csv(pd.DataFrame(ledger), "cleaning_ledger.csv")
    write_csv(comparisons, "quartile_comparisons.csv")
    write_csv(correlations, "spearman_correlations.csv")
    write_csv(boroughs, "borough_summary.csv")
    write_csv(daily.loc[daily.GEOID.notna()].groupby(["borough", "date", "member_casual"], as_index=False).departures.sum(), "daily_borough_departures.csv")
    (PROCESSED / "validation.json").write_text(json.dumps(validation, indent=2, allow_nan=False) + "\n")
    write_cleaning_notes(ledger, validation)
    create_figures(tracts, stations, daily, comparisons, correlations)
    from .verify_figures import verify
    verify()
    if make_report:
        from .report import build_report
        build_report()
    print(json.dumps(validation["counts"], indent=2), flush=True)
    print(f"Analysis and figure generation finished in {time.perf_counter() - started:.1f} seconds.", flush=True)
    return validation


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--skip-report", action="store_true", help="Regenerate data and figures without rebuilding the PDF")
    parser.add_argument("--chunk-size", type=int, default=200_000)
    args = parser.parse_args()
    run(make_report=not args.skip_report, chunk_size=args.chunk_size)
